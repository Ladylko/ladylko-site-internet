function applyDetailTranslations(lang) {
  const t = detailTranslations[lang];
  if (!t) return;
  Object.keys(t).forEach(id => {
    const el = document.getElementById(id);
    if (!el) return;
    el.innerHTML = t[id].includes('\n') ? t[id].replace(/\n/g, '<br>') : t[id];
  });
}

document.addEventListener('DOMContentLoaded', () => applyDetailTranslations(localStorage.getItem('ladylko_lang') || 'fr'));
document.addEventListener('langchange', (e) => applyDetailTranslations(e.detail.lang));
